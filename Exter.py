def normalize_region(place):

    value = re.sub(
        r"\s+",
        " ",
        (place or "").strip()
    )

    upper = value.upper()

    if not upper:
        return (
            "Регион не определён",
            "",
            "Место рождения отсутствует."
        )

    # --------------------------------------------------------
    # Украина
    # --------------------------------------------------------

    for key, region in sorted(
        UA_REGIONS.items(),
        key=lambda x: len(x[0]),
        reverse=True
    ):

        if key in upper:

            return (
                region,
                "Украина",
                "Украинский регион."
            )

    # Если явно указан Крым
    if "КРЫМ" in upper:

        return (
            "Автономная Республика Крым, Украина",
            "Украина",
            "Крым нормализован как украинский регион."
        )

    # Если место рождения явно относится к Украине,
    # но конкретный регион определить невозможно,
    # НЕ подставляем "Украина" как регион.
    if (
        "УКРАИН" in upper
        or "УССР" in upper
    ):

        return (
            "Регион не определён",
            "Украина",
            "Украина указана, но конкретный регион не определён."
        )

    # --------------------------------------------------------
    # Другие страны
    # --------------------------------------------------------

    for country, aliases in COUNTRIES.items():

        for alias in aliases:

            if alias in upper:

                return (
                    country,
                    country,
                    "Страна определена по историческому "
                    "или родительному написанию."
                )

    # --------------------------------------------------------
    # Российские регионы
    # --------------------------------------------------------

    for key, region in sorted(
        REGIONS.items(),
        key=lambda x: len(x[0]),
        reverse=True
    ):

        if key in upper:

            return (
                region,
                "Россия",
                "Регион нормализован "
                "к современному субъекту РФ."
            )

    for key, region in sorted(
        OBLASTS.items(),
        key=lambda x: len(x[0]),
        reverse=True
    ):

        if key in upper:

            return (
                region,
                "Россия",
                "Регион определён "
                "по названию области или края."
            )

    for key, region in sorted(
        CITIES.items(),
        key=lambda x: len(x[0]),
        reverse=True
    ):

        if key in upper:

            return (
                region,
                "Россия",
                "Регион определён "
                "по однозначному названию города."
            )

    # --------------------------------------------------------
    # Исторические названия
    # --------------------------------------------------------

    historical = {

        "ФРУНЗЕ":
            (
                "Кыргызстан",
                "Кыргызстан"
            ),

        "ВОРОШИЛОВГРАД":
            (
                "Луганская область, Украина",
                "Украина"
            ),

        "СТАЛИНО":
            (
                "Донецкая область, Украина",
                "Украина"
            ),

        "ДНЕПРОДЗЕРЖИНСК":
            (
                "Днепропетровская область, Украина",
                "Украина"
            ),

        "ДНЕПРОПЕТРОВСК":
            (
                "Днепропетровская область, Украина",
                "Украина"
            )
    }

    for key, value in historical.items():

        if key in upper:

            return (
                value[0],
                value[1],
                "Историческое название "
                "населённого пункта."
            )

    return (
        "Регион не определён",
        "",
        "Автоматически определить регион "
        "без рискованной догадки невозможно."
    )


