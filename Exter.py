# Словари нормализации не меняются во время работы программы, поэтому
# сортируем их один раз, а не при каждом определении региона.
_SORTED_CONTEXT_REGION_MARKERS = sorted(
    CONTEXT_REGION_MARKERS.items(),
    key=lambda x: len(x[0]),
    reverse=True
)
_SORTED_CITY_REGION_MARKERS = sorted(
    CITY_REGION_MARKERS.items(),
    key=lambda x: len(x[0]),
    reverse=True
)
_SORTED_SPECIAL_TEXT_MARKERS = sorted(
    SPECIAL_TEXT_MARKERS.items(),
    key=lambda x: len(x[0]),
    reverse=True
)


def detect_region(
    place,
    custom_aliases=None
):

    custom_aliases = (
        custom_aliases
        or {}
    )

    clean = (
        place or ""
    ).strip()

    if clean in custom_aliases:

        return custom_aliases[clean]

    if clean in EXTRA_REGION_ALIASES:

        return EXTRA_REGION_ALIASES[clean]

    upper = clean.upper()

    for key, region in _SORTED_CONTEXT_REGION_MARKERS:
        if key in upper:
            return region

    for key, region in _SORTED_CITY_REGION_MARKERS:
        if key in upper:
            return region

    for key, region in _SORTED_SPECIAL_TEXT_MARKERS:
        if key in upper:
            return region

    for alias, region in custom_aliases.items():

        if (
            alias
            and alias.upper() in upper
        ):

            return region

    region, _, _ = normalize_region(
        clean
    )

    return region


