        column = (
            self.current_sort_column
        )

        if column == "fio":

            key_func = lambda x: (
                x.get(
                    "fio",
                    ""
                ).casefold()
            )

        elif column == "birth_date":

            key_func = lambda x: (
                x.get(
                    "birth_date_obj"
                )
                or date.max
            )

        elif column == "birth_year":

            key_func = lambda x: (
                x.get(
                    "birth_year"
                )
                if x.get(
                    "birth_year"
                ) is not None
                else 9999
            )

        elif column == "age":

            key_func = lambda x: (
                x.get("_age")
                if x.get("_age") is not None
                else -1
            )

        elif column == "birth_place":

            key_func = lambda x: (
                x.get(
                    "birth_place",
                    ""
                ).casefold()
            )

        elif column == "region":

            key_func = lambda x: (
                self.region_for_record(
                    x
                ).casefold()
            )

        elif column == "terrorism":

            key_func = lambda x: (
                0
                if x.get(
                    "terrorism_charge",
                    0
                )
                else 1
            )

        else:

            key_func = lambda x: (
                x.get(
                    "fio",
                    ""
                ).casefold()
            )

        rows.sort(
            key=key_func,
            reverse=self.sort_reverse
        )

        for record in rows:

            terrorism = record.get(
                "terrorism_charge",
                0
            )

            terrorism_text = (
                "ТЕРРОРИЗМ"
                if terrorism
                else ""
            )

            age = self.get_age(
                record
            )

            region = (
                self.region_for_record(
                    record
                )
            )

            if region == (
                "Регион не определён"
            ):

                tag = "unknown"

            elif (
                age is not None
                and age < 18
            ):

                tag = "minor"

            elif terrorism:

                tag = "terrorism"

            else:

                tag = "normal"

            self.tree.insert(
                "",
                "end",
                values=(
                    record.get(
                        "fio",
                        ""
                    ),

                    record.get(
                        "birth_date",
                        ""
                    ),

                    record.get(
                        "birth_year"
                    ) or "",

                    age
                    if age is not None
                    else "",

                    record.get(
                        "birth_place",
                        ""
                    ),

                    region,

                    terrorism_text
                ),
                tags=(tag,)
            )

        self.person_counter.configure(
            text=(
                "Показано: {} / {}"
            ).format(
                len(rows),
                len(self.records)
            )
        )



