def html_to_text(source):

    text = source

    text = re.sub(
        r"<script\b[^>]*>.*?</script>",
        " ",
        text,
        flags=re.I | re.S
    )

    text = re.sub(
        r"<style\b[^>]*>.*?</style>",
        " ",
        text,
        flags=re.I | re.S
    )

    text = re.sub(
        r"</?(?:br|p|div|li|tr|h[1-6]|"
        r"section|article|table|thead|tbody|tfoot|ul|ol)"
        r"[^>]*>",
        "\n",
        text,
        flags=re.I
    )

    text = re.sub(
        r"</?(?:td|th)[^>]*>",
        "\t",
        text,
        flags=re.I
    )

    text = re.sub(
        r"<[^>]+>",
        " ",
        text
    )

    text = html.unescape(text)

    text = text.replace(
        "\xa0",
        " "
    )

    lines = []

    for line in text.splitlines():

        line = re.sub(
            r"[ \t]+",
            " ",
            line
        )

        line = line.strip()

        if line:
            lines.append(line)

    return "\n".join(lines)


