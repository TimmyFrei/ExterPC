class Database:

    def __init__(self, path):

        self.con = sqlite3.connect(
            str(path),
            check_same_thread=False
        )

        self.con.execute(
            "PRAGMA foreign_keys = ON"
        )

        self.prepare()


    def prepare(self):

        with self.con:

            self.con.execute(
                """
                CREATE TABLE IF NOT EXISTS organizations (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    name TEXT NOT NULL,
                    details TEXT,
                    terrorism_charge INTEGER
                        NOT NULL DEFAULT 0,
                    raw_text TEXT,
                    imported_at TEXT
                )
                """
            )

            # Добавляем колонку в уже существующую базу,
            # если она была создана старой версией программы.
            organization_columns = {
                row[1]
                for row in self.con.execute(
                    "PRAGMA table_info(organizations)"
                ).fetchall()
            }

            if "terrorism_charge" not in organization_columns:
                self.con.execute(
                    """
                    ALTER TABLE organizations
                    ADD COLUMN terrorism_charge
                    INTEGER NOT NULL DEFAULT 0
                    """
                )

            self.con.execute(
                """
                CREATE INDEX IF NOT EXISTS
                idx_organizations_terrorism
                ON organizations(terrorism_charge)
                """
            )
            # ------------------------------------------------
            # ТАБЛИЦА ЛЮДЕЙ
            # ------------------------------------------------

            self.con.execute(
                """
                CREATE TABLE IF NOT EXISTS persons (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    fio TEXT NOT NULL,
                    birth_date TEXT,
                    birth_year INTEGER,
                    birth_place TEXT,
                    terrorism_charge INTEGER NOT NULL DEFAULT 0,
                    raw_text TEXT,
                    imported_at TEXT
    )
    """
)
            # ------------------------------------------------
            # МИГРАЦИЯ СТАРОЙ БАЗЫ
            # ------------------------------------------------

            columns = {
                row[1]
                for row in self.con.execute(
                    "PRAGMA table_info(persons)"
                ).fetchall()
            }

            required_columns = {

                "birth_date": "TEXT",

                "birth_year": "INTEGER",

                "birth_place": "TEXT",

                "terrorism_charge":
                    "INTEGER NOT NULL DEFAULT 0",

                "raw_text": "TEXT",

                "imported_at": "TEXT"
            }

            for column, definition in (
                required_columns.items()
            ):

                if column not in columns:

                    self.con.execute(
                        "ALTER TABLE persons "
                        "ADD COLUMN {} {}".format(
                            column,
                            definition
                        )
                    )

            # ------------------------------------------------
            # СТАРАЯ ВЕРСИЯ МОГЛА ИМЕТЬ terrorism
            # ------------------------------------------------

            columns = {
                row[1]
                for row in self.con.execute(
                    "PRAGMA table_info(persons)"
                ).fetchall()
            }

            if (
                "terrorism"
                in columns
                and "terrorism_charge"
                in columns
            ):

                self.con.execute(
                    """
                    UPDATE persons
                    SET terrorism_charge = terrorism
                    WHERE terrorism_charge IS NULL
                    """
                )

            self.con.execute(
                """
                CREATE INDEX IF NOT EXISTS
                idx_persons_fio
                ON persons(fio)
                """
            )

            self.con.execute(
                """
                CREATE INDEX IF NOT EXISTS
                idx_persons_birth_year
                ON persons(birth_year)
                """
            )

            self.con.execute(
                """
                CREATE INDEX IF NOT EXISTS
                idx_persons_terrorism
                ON persons(terrorism_charge)
                """
            )

            # ------------------------------------------------
            # ОРГАНИЗАЦИИ
            # ------------------------------------------------
            self.con.execute(
                """
                CREATE TABLE IF NOT EXISTS organizations (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    name TEXT NOT NULL,
                    details TEXT,
                    raw_text TEXT,
                    imported_at TEXT
                )
                """
            )

            self.con.execute(
                """
                CREATE INDEX IF NOT EXISTS
                idx_organizations_name
                ON organizations(name)
                """
            )

            # ------------------------------------------------
            # РУЧНЫЕ СООТВЕТСТВИЯ
            # ------------------------------------------------

            self.con.execute(
                """
                CREATE TABLE IF NOT EXISTS region_aliases (
                    alias TEXT PRIMARY KEY,
                    region TEXT NOT NULL
                )
                """
            )


    def clear_persons(self):

        with self.con:

            self.con.execute(
                "DELETE FROM persons"
            )


    def add_person(
        self,
        fio,
        birth_date,
        birth_year,
        birth_place,
        terrorism_charge,
        raw_text
    ):

        self.con.execute(
            """
            INSERT INTO persons (
                fio,
                birth_date,
                birth_year,
                birth_place,
                terrorism_charge,
                raw_text,
                imported_at
            )
            VALUES (?, ?, ?, ?, ?, ?, ?)
            """,
            (
                fio,
                birth_date,
                birth_year,
                birth_place,
                terrorism_charge,
                raw_text,
                datetime.now().isoformat(
                    " ",
                    "seconds"
                )
            )
        )


    def add_people(self, records):

        now = datetime.now().isoformat(
            " ",
            "seconds"
        )

        rows = [
            (
                record["fio"],
                record["birth_date"],
                record["birth_year"],
                record["birth_place"],
                record["terrorism_charge"],
                record["raw_text"],
                now
            )
            for record in records
        ]

        self.con.executemany(
            """
            INSERT INTO persons (
                fio,
                birth_date,
                birth_year,
                birth_place,
                terrorism_charge,
                raw_text,
                imported_at
            )
            VALUES (?, ?, ?, ?, ?, ?, ?)
            """,
            rows
        )


    def clear_organizations(self):

        with self.con:
            self.con.execute(
                "DELETE FROM organizations"
            )


    def add_organizations(self, records):

        if not records:
            return

        now = datetime.now().isoformat(
            " ",
            "seconds"
        )

        rows = [
            (
                record["name"],
                record.get("details", ""),
                record.get("terrorism_charge", 0),
                record.get("raw_text", ""),
                now
            )
            for record in records
        ]

        self.con.executemany(
            """
            INSERT INTO organizations (
                name,
                details,
                terrorism_charge,
                raw_text,
                imported_at
            )
            VALUES (?, ?, ?, ?, ?)
            """,
            rows
        )

    def commit(self):

        self.con.commit()


    def close(self):

        self.con.close()


