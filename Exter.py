def parse_organizations_from_html(source):

    if not source:
        return []

    match = re.search(
        r'<div\s+id=["\']russianUL["\'][^>]*>(.*?)</div>\s*\s*<div',
        source,
        flags=re.IGNORECASE | re.DOTALL
    )

    if not match:
        match = re.search(
            r'<div\s+id=["\']russianUL["\'][^>]*>(.*?)(?=<div\s+id=["\']russian[A-Za-z]+["\'])',
            source,
            flags=re.IGNORECASE | re.DOTALL
        )

    if not match:
        return []

    block = match.group(1)
    items = re.findall(
        r'<li\b[^>]*>(.*?)</li>',
        block,
        flags=re.IGNORECASE | re.DOTALL
    )

    records = []

    for item in items:
        text = re.sub(r'<[^>]+>', ' ', item)
        text = html.unescape(text)
        text = text.replace('\xa0', ' ')
        text = re.sub(r'[ \t\r\n]+', ' ', text).strip()
        text = re.sub(r'^\s*\d+\s*[\.)]\s*', '', text).strip()
        text = re.sub(r'\s*,\s*;\s*$', '', text).strip()
        text = re.sub(r'\s*;\s*$', '', text).strip()

        if not text:
            continue

        # В названиях встречаются запятые внутри скобок. Поэтому
        # разделяем название и дополнительные сведения только по
        # первой запятой, находящейся вне скобок.
        separator = None
        depth = 0

        for index, char in enumerate(text):
            if char == '(':
                depth += 1
            elif char == ')' and depth > 0:
                depth -= 1
            elif char == ',' and depth == 0:
                separator = index
                break

        if separator is not None:
            name = text[:separator].strip()
            details = text[separator + 1:].strip(' ,')
        else:
            name = text
            details = ''

        # Организации со звёздочкой имеют отметку о террористическом характере
        terrorism_charge = (
            1
            if name.rstrip().endswith("*")
            else 0
        )

        # Звёздочка нужна только как служебная отметка,
        # в названии организации её не показываем.
        name = name.rstrip().rstrip("*").rstrip()

        records.append({
            'name': name,
            'details': details,
            'terrorism_charge': terrorism_charge,
            'raw_text': text
        })

    return records


