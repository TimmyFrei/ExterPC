    def update_from_site(self):

        self.status_var.set(
            "Загрузка сайта..."
        )

        self.progress.start(
            10
        )

        thread = threading.Thread(
            target=self.download_thread
        )

        thread.daemon = True

        thread.start()


    def download_thread(self):

        try:

            source = download_page()

            text = html_to_text(
                source
            )

            self.after(
                0,
                lambda: self.download_success(
                    source,
                    text
                )
            )

        except HTTPError as exc:

            self.after(
                0,
                lambda: self.download_error(
                    "HTTP ошибка {}.".format(
                        exc.code
                    )
                )
            )

        except URLError as exc:

            self.after(
                0,
                lambda: self.download_error(
                    str(exc)
                )
            )

        except Exception as exc:

            self.after(
                0,
                lambda: self.download_error(
                    "{}: {}".format(
                        type(exc).__name__,
                        exc
                    )
                )
            )


    def download_success(
        self,
        source,
        text
    ):

        self.progress.stop()

        self.page_html = source

        self.page_text = text

        try:

            with open(
                DEBUG_HTML,
                "w",
                encoding="utf-8"
            ) as f:

                f.write(
                    source
                )

            with open(
                DEBUG_TEXT,
                "w",
                encoding="utf-8"
            ) as f:

                f.write(
                    text
                )

        except Exception:
            pass

        self.status_var.set(
            "Сайт загружен. Начинаю импорт..."
        )

        thread = threading.Thread(
            target=self.import_thread
        )

        thread.daemon = True

        thread.start()


    def import_thread(self):

        parsed_people = parse_people_from_text(
            self.page_text
        )

        parsed_organizations = parse_organizations_from_html(
            self.page_html
        )

        self.after(
            0,
            lambda: self.import_records(
                parsed_people,
                parsed_organizations
            )
        )


    def import_records(
        self,
        records,
        organizations=None
    ):

        try:

            if not records:

                preview = (
                    self.page_text[:1000]
                )

                raise RuntimeError(
                    (
                        "Не удалось найти записи "
                        "физических лиц.\n\n"
                        "Загруженный текст сохранён в:\n"
                        "{}\n\n"
                        "Первые 1000 символов:\n\n{}"
                    ).format(
                        DEBUG_TEXT,
                        preview
                    )
                )

            if organizations is None:
                organizations = []

            self.db.clear_persons()
            self.db.clear_organizations()

            self.db.add_people(records)
            self.db.add_organizations(organizations)
            self.db.commit()

            self.records = records
            self.organizations = organizations
            self.prepare_record_cache()
            self.update_filter_values()

            self.refresh_table()

            self.refresh_statistics()

            terrorism_count = sum(
                1
                for x in records
                if x.get(
                    "terrorism_charge",
                    0
                )
            )

            unknown_count = sum(
                1
                for x in records
                if self.region_for_record(
                    x
                ) == "Регион не определён"
            )

            self.refresh_organizations_table()

            self.status_var.set(
                "Импорт завершён: {} физлиц, {} организаций.".format(
                    len(records),
                    len(organizations)
                )
            )

            messagebox.showinfo(
                "Импорт завершён",
                (
                    "Найдено записей: {}\n\n"
                    "С отметкой об обвинении "
                    "в терроризме: {}\n\n"
                    "Без этой отметки: {}\n\n"
                    "Регион не определён: {}"
                ).format(
                    len(records),
                    terrorism_count,
                    len(records)
                    - terrorism_count,
                    unknown_count
                ),
                parent=self
            )

        except Exception as exc:

            self.progress.stop()

            messagebox.showerror(
                "Ошибка импорта",
                str(exc),
                parent=self
            )


