    def get_filtered_records(self):

        search = (
            self.search_var.get()
            .strip()
            .lower()
        )

        year = (
            self.year_var.get()
        )

        terrorism = (
            self.terrorism_var.get()
        )

        region = (
            self.region_var.get()
        )

        minor_only = (
            self.minor_var.get()
        )

        rows = []

        for record in self.records:

            if search:

                if "_search_text" not in record:
                    self.prepare_record_cache([record])

                combined = record["_search_text"]

                if search not in combined:
                    continue

            if year != "Все":

                if str(
                    record.get(
                        "birth_year"
                    )
                ) != year:

                    continue

            if terrorism == "С обвинением":

                if not record.get(
                    "terrorism_charge",
                    0
                ):

                    continue

            elif terrorism == "Без обвинения":

                if record.get(
                    "terrorism_charge",
                    0
                ):

                    continue

            if region != "Все":

                if self.region_for_record(record) != region:

                    continue

            if minor_only:

                age = self.get_age(
                    record
                )

                if age is None:
                    continue

                if age >= 18:
                    continue

            rows.append(
                record
            )

        return rows


