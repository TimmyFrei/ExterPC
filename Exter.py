    def load_custom_region_aliases(self):

        try:

            rows = self.db.con.execute(
                """
                SELECT alias, region
                FROM region_aliases
                """
            ).fetchall()

            self.custom_region_aliases = {
                alias: region
                for alias, region in rows
            }

        except Exception:

            self.custom_region_aliases = {}


    def save_custom_region_alias(
        self,
        alias,
        region
    ):

        alias = alias.strip()

        region = region.strip()

        if not alias or not region:
            return

        self.db.con.execute(
            """
            INSERT OR REPLACE INTO
            region_aliases(
                alias,
                region
            )
            VALUES (?, ?)
            """,
            (
                alias,
                region
            )
        )

        self.db.commit()

        self.custom_region_aliases[
            alias
        ] = region

        # Новое ручное соответствие может изменить уже рассчитанные регионы.
        self.invalidate_record_cache()


    def prepare_record_cache(
        self,
        records=None
    ):

        records = (
            self.records
            if records is None
            else records
        )

        for record in records:

            region = detect_region(
                record.get(
                    "birth_place",
                    ""
                ),
                self.custom_region_aliases
            )

            birth_date = record.get(
                "birth_date_obj"
            )

            if birth_date is None:
                birth_date = parse_date(
                    record.get(
                        "birth_date"
                    )
                )
                record["birth_date_obj"] = birth_date

            age = calculate_age(
                birth_date
            )

            record["_region"] = region
            record["_country"] = country_for_region_value(region)
            record["_age"] = age
            record["_search_text"] = (
                record.get("fio", "")
                + " "
                + record.get("birth_place", "")
                + " "
                + region
            ).lower()


    def invalidate_record_cache(
        self
    ):

        self.prepare_record_cache()


    def region_for_record(
        self,
        record
    ):

        if "_region" not in record:
            self.prepare_record_cache([record])

        return record["_region"]


