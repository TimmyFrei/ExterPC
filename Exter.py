PERSON_PATTERN = re.compile(
    r"^\s*"
    r"(?:\d+\s*[\.\)]\s*)*"
    r"(?P<fio>.*?)"
    r"\s*,\s*"
    r"(?P<date>\d{2}\.\d{2}\.\d{4})"
    r"\s*г\.р\."
    r"\s*,\s*"
    r"(?P<place>.*?)"
    r"\s*;?\s*$",
    re.IGNORECASE
)


def parse_person_line(line):

    line = line.strip()

    if not line:
        return None

    match = PERSON_PATTERN.match(line)

    if not match:
        return None

    fio_raw = match.group(
        "fio"
    ).strip()

    birth_date = match.group(
        "date"
    ).strip()

    birth_place = match.group(
        "place"
    ).strip()

    terrorism_charge = (
        1
        if fio_raw.endswith("*")
        else 0
    )

    fio = fio_raw.rstrip(
        "*"
    ).strip()

    if not fio:
        return None

    parsed_date = parse_date(
        birth_date
    )

    return {
        "fio": fio,
        "birth_date": birth_date,
        "birth_date_obj": parsed_date,
        "birth_year": (
            parsed_date.year
            if parsed_date
            else None
        ),
        "birth_place": birth_place,
        "terrorism_charge": terrorism_charge,
        "raw_text": line
    }


def parse_people_from_text(text):

    records = []

    for line in text.splitlines():

        record = parse_person_line(
            line
        )

        if record is not None:
            records.append(
                record
            )

    return records


