    def refresh_region_statistics(self):

        if not hasattr(
            self,
            "region_stats_tree"
        ):
            return

        records = (
            self.filtered_statistics_records()
        )

        grouped = {}

        for record in records:

            region = self.region_for_record(
                record
            )

            grouped[region] = (
                grouped.get(region, 0)
                + 1
            )

        items = sorted(
            grouped.items(),
            key=lambda x: (
                -x[1]
                if self.region_sort_desc
                else x[1],
                x[0].casefold()
            )
        )

        for item in (
            self.region_stats_tree.get_children()
        ):
            self.region_stats_tree.delete(
                item
            )

        for region, count in items:

            self.region_stats_tree.insert(
                "",
                "end",
                values=(
                    region,
                    count
                )
            )

        # ----------------------------------------------------
        # Обновляем подпись сортировки
        # ----------------------------------------------------

        if self.region_sort_desc:

            self.region_stats_tree.heading(
                "count",
                text="Количество ↓",
                command=self.toggle_region_sort
            )

        else:

            self.region_stats_tree.heading(
                "count",
                text="Количество ↑",
                command=self.toggle_region_sort
            )

    def filtered_statistics_records(self):

        mode = self.stats_mode.get()

        if mode == "С обвинением":

            return [
                x
                for x in self.records
                if x.get(
                    "terrorism_charge",
                    0
                )
            ]

        if mode == "Без обвинения":

            return [
                x
                for x in self.records
                if not x.get(
                    "terrorism_charge",
                    0
                )
            ]

        return list(
            self.records
        )

    def refresh_statistics(self):

        if not hasattr(
            self,
            "year_ax"
        ):
            return

        records = (
            self.filtered_statistics_records()
        )

        terrorism_count = sum(
            1
            for x in records
            if x.get(
                "terrorism_charge",
                0
            )
        )

        minors_count = sum(
            1
            for x in records
            if (
                self.get_age(x)
                is not None
                and self.get_age(x) < 18
            )
        )

        unknown_count = sum(
            1
            for x in records
            if (
                self.region_for_record(x)
                == "Регион не определён"
            )
        )

        self.stats_counter.configure(
            text=(
                "Записей: {}    "
                "С отметкой о терроризме: {}    "
                "Несовершеннолетних: {}    "
                "Регион не определён: {}"
            ).format(
                len(records),
                terrorism_count,
                minors_count,
                unknown_count
            )
        )

        # ----------------------------------------------------
        # ГОДЫ
        # ----------------------------------------------------

        year_counts = {}

        for record in records:

            year = record.get(
                "birth_year"
            )

            if year is None:
                continue

            year_counts[year] = (
                year_counts.get(
                    year,
                    0
                )
                + 1
            )

        years = sorted(
            year_counts.keys()
        )

        counts = [
            year_counts[y]
            for y in years
        ]

        self.year_ax.clear()

        if years:

            x = list(
                range(
                    len(years)
                )
            )

            bars = self.year_ax.bar(
                x,
                counts
            )

            self.year_ax.set_xticks(
                x
            )

            self.year_ax.set_xticklabels(
                [str(y) for y in years],
                rotation=90,
                fontsize=8
            )

            self.year_ax.set_ylabel(
                "Количество"
            )

            self.year_ax.set_xlabel(
                "Год рождения"
            )

            self.year_ax.set_title(
                "Распределение по годам рождения"
            )

            self.year_ax.grid(
                axis="y",
                alpha=0.25
            )

            for bar, count in zip(
                bars,
                counts
            ):

                self.year_ax.text(
                    bar.get_x()
                    + bar.get_width() / 2,
                    bar.get_height(),
                    str(count),
                    ha="center",
                    va="bottom",
                    fontsize=8
                )

            self.year_figure.subplots_adjust(
                bottom=0.28,
                left=0.08,
                right=0.98,
                top=0.90
            )

        else:

            self.year_ax.text(
                0.5,
                0.5,
                "Нет данных",
                ha="center",
                va="center",
                transform=self.year_ax.transAxes
            )

